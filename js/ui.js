function icon(name) {
  return ICONS[name] || "";
}

function initialsAvatar(userId, size) {
  const u = getUser(userId);
  const cls = size ? "avatar " + size : "avatar";
  return `<div class="${cls}" style="background:${u.color}" data-tooltip="${escapeHtml(u.name)}">${initials(u.name)}</div>`;
}

function projectChip(projectId) {
  const p = getProject(projectId);
  return `<span class="project-chip"><span class="project-dot" style="background:${p.color}"></span>${escapeHtml(p.name)}</span>`;
}

function statusBadge(status) {
  return `<span class="badge ${statusBadgeClass(status)}">${escapeHtml(status)}</span>`;
}

function priorityBadge(priority) {
  return `<span class="badge ${priorityBadgeClass(priority)}">${escapeHtml(priority)}</span>`;
}

function escapeHtml(str) {
  if (str == null) return "";
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/* ---------- Toasts ---------- */
function showToast(message, type) {
  let wrap = document.querySelector(".toast-wrap");
  if (!wrap) {
    wrap = document.createElement("div");
    wrap.className = "toast-wrap";
    document.body.appendChild(wrap);
  }
  const el = document.createElement("div");
  el.className = "toast" + (type ? " " + type : "");
  el.innerHTML = `${type === "success" ? icon("check") : ""}<span>${escapeHtml(message)}</span>`;
  wrap.appendChild(el);
  setTimeout(() => {
    el.style.transition = "opacity 0.2s ease";
    el.style.opacity = "0";
    setTimeout(() => el.remove(), 200);
  }, 2400);
}

/* ---------- Theme ----------
   A per-browser preference, deliberately kept out of Store/the server — everyone on
   the shared team data can have their own light/dark choice. */
const THEME_KEY = "workflow_theme_pref";

function getThemePref() {
  return localStorage.getItem(THEME_KEY);
}

function applyTheme() {
  const pref = getThemePref();
  if (pref === "dark") document.documentElement.setAttribute("data-theme", "dark");
  else if (pref === "light") document.documentElement.setAttribute("data-theme", "light");
  else document.documentElement.removeAttribute("data-theme");
}

function isDarkActive() {
  const pref = getThemePref();
  if (pref === "dark") return true;
  if (pref === "light") return false;
  return window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches;
}

function toggleTheme() {
  localStorage.setItem(THEME_KEY, isDarkActive() ? "light" : "dark");
  applyTheme();
  renderThemeIcon();
}

function renderThemeIcon() {
  const el = document.getElementById("themeToggleIcon");
  if (el) el.innerHTML = isDarkActive() ? icon("sun") : icon("moon");
}
